export const isVideoMedia = (url?: string): boolean => {
  if (!url) return false;
  return (
    url.endsWith('.mp4') ||
    url.endsWith('.webm') ||
    url.endsWith('.mov') ||
    url.includes('/videos/') ||
    url.includes('mixkit.co')
  );
};

